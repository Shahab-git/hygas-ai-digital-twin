"""Documented process links between registry items (BL-3). Pure Python, no Blender.

SOURCE OF TRUTH: the live engine's own same-cycle dependency graph (`depends_on` of every registered model in
python/tab1_integration.build_engine()). Nothing here is read from a drawing, a P&ID or the registry (the registry has no connection
data). A link A -> B means: the model of B reads a value computed by the model of A. That is a DOCUMENTED MODEL DEPENDENCY, not a
verified pipe or conveyor route and it does not say which medium flows.

FILTER (rule, not hand-picked): both ends must be physical process equipment. Dropped: instruments/analysers/meters (SA-*, FE-006,
EU-009, EU-010, EU-013, EU-001..003 parameter slices), the AI/software items and the `*-INPUT` pseudo keys. Lagged dependencies are not
links (they are per-cycle couplings). The generated file data/plant_links.json is compared with the live engine by a test.
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
LINKS_JSON = os.path.join(ROOT, "data", "plant_links.json")

PHYSICAL = {
    "FE": {"FE-001", "FE-002", "FE-003", "FE-004", "FE-005", "FE-007", "FE-008"},
    "GA": {"GA-001", "GA-003", "GA-005", "GA-006", "GA-007", "GA-008", "GA-009", "GA-010"},
    "GC": {"GC-001", "GC-003", "GC-004", "GC-006", "GC-007", "GC-008", "GC-009", "GC-010", "GC-012", "GC-013", "GC-015"},
    "HB": {"HB-001", "HB-003", "HB-004", "HB-005", "HB-006", "HB-009", "HB-010", "HB-011", "HB-012", "HB-013", "HB-014", "HB-015",
           "HB-016", "HB-017", "HB-018"},
    "EU": {"EU-004", "EU-005", "EU-006", "EU-007", "EU-008", "EU-011", "EU-012"},
}
PHYSICAL_IDS = set().union(*PHYSICAL.values())
_ID = re.compile(r"^[A-Z]{2}-\d{3}$")


def _tag_target(layout_tags):
    return dict(layout_tags)


def derive_from_engine():
    """Edges (source_id, target_id) from the real engine, filtered as described. Imports the engine (numpy etc.)."""
    sys.path.insert(0, ROOT)
    from python import tab1_integration as t
    _state, engine = t.build_engine()
    edges = set()
    for key, spec in engine._models.items():
        a = key[0] if isinstance(key, tuple) else str(key)
        for dep in spec["depends_on"]:
            b = dep[0] if isinstance(dep, tuple) else str(dep)
            if _ID.match(a) and _ID.match(b) and a != b and a in PHYSICAL_IDS and b in PHYSICAL_IDS:
                edges.add((b, a))
    return sorted(edges)


def load_links():
    with open(LINKS_JSON, encoding="utf-8") as fh:
        return [tuple(e) for e in json.load(fh)["links"]]


def write_links():
    edges = derive_from_engine()
    doc = {"note": __doc__.strip().split("\n")[0] + " Generated by `python blender/plant_links.py --write`; compared with the engine by "
                   "tests/test_blender_links.py. A link is a model dependency, NOT a verified pipe.",
           "source": "python/tab1_integration.build_engine() depends_on", "links": [list(e) for e in edges]}
    with open(LINKS_JSON, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(doc, fh, indent=1)
        fh.write("\n")
    return edges


if __name__ == "__main__":
    if "--write" in sys.argv:
        print(len(write_links()), "links written to", LINKS_JSON)
    else:
        print(len(derive_from_engine()), "links")


# ---------------------------------------------------------------------------------------------------------------- routing
# SCHEMATIC routing of the documented links (pure Python so CI can test it without Blender). The route is an ASSUMPTION:
# straight low run between neighbours in a lane when nothing stands in the way, otherwise an overhead orthogonal run above every
# item it passes. It is NOT a piping isometric. Diameters are ASSUMED (PIPE_R).
PLINTH = 0.12            # same as generate_plant.PLINTH
PIPE_R = 0.06            # assumed pipe outer radius (m), schematic
CLEAR = 1.0              # clearance of an overhead run above the tallest item it passes (m), assumed
LEVEL = 0.35             # vertical spacing between overhead runs (m), assumed
LOW_Y_STEP = 0.14        # lateral spacing of low runs that share a lane (m), assumed


def _host(i, tag_of):
    return tag_of.get(i, i)


def _box(it):
    return (it["x"] - it["w"] / 2, it["y"] - it["d"] / 2, it["x"] + it["w"] / 2, it["y"] + it["d"] / 2, PLINTH + it["h"])


def route_all(layout, links=None):
    """layout: list of item dicts from plant_layout.build_layout(). Returns [{from,to,points,kind,supports}] in a fixed order."""
    sys.path.insert(0, os.path.join(ROOT, "blender"))
    import plant_layout as L
    links = links if links is not None else load_links()
    by_id = {i["id"]: i for i in layout}
    boxes = {i["id"]: _box(i) for i in layout if not i["tag_of"] and i["id"] not in L.NON_PHYSICAL}
    used = {}
    routes = []
    for n, (a, b) in enumerate(links):
        ha, hb = _host(a, L.TAG_OF), _host(b, L.TAG_OF)
        A, B = by_id[ha], by_id[hb]
        ba, bb = boxes[ha], boxes[hb]
        others = [v for k, v in boxes.items() if k not in (ha, hb)]
        lane_dy = abs(A["y"] - B["y"])
        x0, x1 = sorted((A["x"], B["x"]))
        blocked = any(o[0] < x1 and o[2] > x0 and o[1] < max(A["y"], B["y"]) + 0.6 and o[3] > min(A["y"], B["y"]) - 0.6 for o in others)
        if lane_dy < 1.0 and not blocked and A["x"] != B["x"]:
            s = 1 if B["x"] > A["x"] else -1
            zp = PLINTH + min(A["h"], B["h"]) * 0.5
            zp = max(zp, PLINTH + 0.25)
            lane_key = round(A["y"])
            k = used.get(("low", lane_key), 0)
            used[("low", lane_key)] = k + 1
            ya = A["y"] + ((k % 3) - 1) * LOW_Y_STEP
            yb = B["y"] + ((k % 3) - 1) * LOW_Y_STEP
            xa = A["x"] + s * A["w"] / 2
            xb = B["x"] - s * B["w"] / 2
            xm = (xa + xb) / 2
            pts = [(xa, ya, zp), (xm, ya, zp), (xm, yb, zp), (xb, yb, zp)] if abs(ya - yb) > 1e-6 else [(xa, ya, zp), (xb, yb, zp)]
            pts = [q for i, q in enumerate(pts) if i == 0 or q != pts[i - 1]]
            routes.append({"from": a, "to": b, "kind": "low", "points": pts, "supports": []})
            continue
        # overhead run
        ia = used.get(("riser", ha), 0)
        ib = used.get(("riser", hb), 0)
        used[("riser", ha)] = ia + 1
        used[("riser", hb)] = ib + 1
        ax = A["x"] + (min(ia, 2) - 1) * 0.07 * min(A["w"] / 0.4, 3)
        ay = A["y"] + (ia // 3) * 0.08
        bx = B["x"] + (min(ib, 2) - 1) * 0.07 * min(B["w"] / 0.4, 3)
        by = B["y"] + (ib // 3) * 0.08
        lo_x, hi_x = min(ax, bx) - 0.5, max(ax, bx) + 0.5
        lo_y, hi_y = min(ay, by) - 0.5, max(ay, by) + 0.5
        top = max([o[4] for o in others if o[0] < hi_x and o[2] > lo_x and o[1] < hi_y and o[3] > lo_y] + [ba[4], bb[4]])
        lvl = used.get(("level", int(top)), 0)
        used[("level", int(top))] = lvl + 1
        zr = top + CLEAR + LEVEL * (lvl % 6)
        pts = [(ax, ay, ba[4]), (ax, ay, zr), (bx, ay, zr), (bx, by, zr), (bx, by, bb[4])]
        pts = [p for i, p in enumerate(pts) if i == 0 or p != pts[i - 1]]
        sup = []
        for p, q in zip(pts, pts[1:]):
            if p[2] == q[2] and ((p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2) ** 0.5 > 6.0:
                mx, my = (p[0] + q[0]) / 2, (p[1] + q[1]) / 2
                if not any(o[0] - 0.3 < mx < o[2] + 0.3 and o[1] - 0.3 < my < o[3] + 0.3 for o in boxes.values()):
                    sup.append((mx, my, zr))
        routes.append({"from": a, "to": b, "kind": "overhead", "points": pts, "supports": sup})
    return routes


def segment_hits_box(p, q, box, eps=1e-6):
    """True if the segment p-q passes through the box (x0,y0,x1,y1,top) with its floor at z=0 (strict interior, with tolerance)."""
    n = 40
    for i in range(n + 1):
        t = i / n
        x, y, z = (p[0] + (q[0] - p[0]) * t, p[1] + (q[1] - p[1]) * t, p[2] + (q[2] - p[2]) * t)
        if box[0] + eps < x < box[2] - eps and box[1] + eps < y < box[3] - eps and eps < z < box[4] - 1e-3:
            return True
    return False
