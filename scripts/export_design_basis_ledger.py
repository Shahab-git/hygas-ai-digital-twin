"""
Design-basis ledger export (task A3). Writes docs/design_basis_ledger.md and docs/design_basis_ledger.csv from parameter_table.build_ledger(), the coverage scan and
data/ledger_exceptions.json. Both files are COMMITTED and GENERATED: tests/test_design_basis_ledger.py fails if they differ from a fresh generation, so a change to a
constant, a status or a consumer must be followed by re-running this script.

    python scripts/export_design_basis_ledger.py        (from the repo root, a few seconds)

Offline: the engine run that records which model reads which input uses the in-memory fake store (no database, no network, no secrets.toml). Nothing is written but the two files.
"""
import collections
import csv
import io
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tests"))
if os.environ.get("HYGAS_ALLOW_DB_WRITES") == "1":
    sys.exit("Refusing to run: HYGAS_ALLOW_DB_WRITES=1 is set. This script never writes to a database; unset it.")

from _fakes import FakeSupabase, patched_supabase       # noqa: E402
from python import ledger_anchors, ledger_consumers, ledger_coverage as lc, ledger_notes, parameter_table as pt    # noqa: E402
from python import tab1_integration as t1               # noqa: E402

MD_PATH = os.path.join(ROOT, "docs", "design_basis_ledger.md")
CSV_PATH = os.path.join(ROOT, "docs", "design_basis_ledger.csv")
N_CYCLES = 3


def build():
    """(ledger rows, scan items, exceptions, instrumented readers). The engine is run once with its get_input recorded (ledger_consumers.record_reads)."""
    with patched_supabase(FakeSupabase()):
        readers = ledger_consumers.engine_input_readers(lambda: t1.build_live_snapshot(N_CYCLES))
    return pt.build_ledger(readers=readers), lc.scan(), lc.load_exceptions(), readers


def _v(x):
    if x is None:
        return "Missing"
    if isinstance(x, float):
        return repr(x)
    if isinstance(x, (list, tuple)):
        return "[" + ", ".join(_v(i) for i in x) + "]"
    if isinstance(x, dict):
        return "{" + ", ".join(f"{k}: {_v(i)}" for k, i in x.items()) + "}"
    return str(x)


# task A3c: the committed export names WHERE a value lives by symbol (`anchor`), never by line, and carries no code line numbers in its text, so it does not go stale when a line is added
# above a ledgered constant. build_ledger() still has `file_line` for interactive use.
EXPORT_COLUMNS = tuple("anchor" if c == "file_line" else c for c in pt.LEDGER_COLUMNS if c != "anchor")


def _cell(row, col):
    return ledger_anchors.strip_code_lines(_v(row[col]))


def _cons(row):
    return "; ".join(row["consumers"]) if row["consumers"] else "NONE FOUND"


def render_csv(ledger):
    out = io.StringIO()
    w = csv.writer(out, lineterminator="\n")
    w.writerow(EXPORT_COLUMNS)
    for r in ledger:
        w.writerow([_cons(r) if c == "consumers" else "; ".join(r[c]) if c == "upgrade_question" else (r[c] or "") if c == "source_line" else _cell(r, c) for c in EXPORT_COLUMNS])
    return out.getvalue()


def counts(ledger, items, exceptions):
    return {
        "rows": len(ledger), "ledger_ids": len({r["ledger_id"] for r in ledger}),
        "by_status": dict(sorted(collections.Counter(r["status"] for r in ledger).items())),
        "by_origin": dict(sorted(collections.Counter(r["origin"] for r in ledger).items())),
        "by_via": dict(sorted(collections.Counter(r["overridable_via"] for r in ledger).items())),
        "by_via_status": dict(sorted(collections.Counter("own" if r["status_via"] == "own" else "registry counterpart" for r in ledger).items())),
        "no_consumer": sorted(f"{r['ledger_id']} ({r['overridable_via']})" for r in ledger if not r["consumers"]),
        "no_question": sum(1 for r in ledger if not r["upgrade_question"]),
        "items": len(items), "by_kind": dict(sorted(collections.Counter(i["kind"] for i in items).items())),
        "exceptions": len(exceptions), "by_class": dict(sorted(collections.Counter(e["class"] for e in exceptions).items())),
    }


def render_md(ledger, items, exceptions):
    c = counts(ledger, items, exceptions)
    L = ["# Design-basis ledger", "",
         "Generated by `scripts/export_design_basis_ledger.py` (task A3) from `parameter_table.build_ledger()`, `python/ledger_coverage.py` and `data/ledger_exceptions.json`; "
         "`tests/test_design_basis_ledger.py` fails if this file or `design_basis_ledger.csv` differs from a fresh generation. Nothing in it is a second copy of a value: each row "
         "names where it lives by symbol (`anchor`, never a line number), so it does not go stale when a line is added above a constant.", "",
         "Statuses are the project's: Confirmed (DOK-ING source cited), Calculated, Estimated, Assumed, Missing, plus Unverified (registry). A row with a registry counterpart takes the "
         "status, `origin` and `source_line` the provenance overlay (`data/registry_status_overlay.json`) gives that registry row; any other row is Assumed and says so "
         "(`STATUS ASSIGNED BY THIS TABLE`). `origin` is `NOT STATED` where the owner's worksheet has no answer for the row. `consumers` lists the engine keys that really call "
         "`get_input` for an engine input (an instrumented run), and the functions that name the constant otherwise (`ast`); `NONE FOUND` is reported, not hidden. "
         "`upgrade_question` is empty where the repo holds no question that would upgrade the row; no question was invented.", "",
         "## Counts", "",
         f"- Rows: **{c['rows']}** ({c['ledger_ids']} distinct `ledger_id`; a quantity held in two places has two rows with the same id and different `source`).",
         f"- By status: {', '.join(f'{k} {v}' for k, v in c['by_status'].items())}.",
         f"- By `status_via`: {', '.join(f'{k} {v}' for k, v in c['by_via_status'].items())}.",
         f"- By origin (provenance overlay): {', '.join(f'{k} {v}' for k, v in c['by_origin'].items())}.",
         f"- By `overridable_via`: {', '.join(f'{k} {v}' for k, v in c['by_via'].items())}.",
         f"- Rows with no `upgrade_question` (no question in the repo would upgrade them): **{c['no_question']}**.",
         f"- Rows with no consumer found ({len(c['no_consumer'])}): {', '.join('`%s`' % i for i in c['no_consumer'])}.",
         f"- Coverage scan of the {len(lc.SCAN_MODULES)} modules that feed published keys: **{c['items']}** numeric items ({', '.join(f'{k} {v}' for k, v in c['by_kind'].items())}); "
         f"**{c['items'] - c['exceptions']}** are PARAMETERs (every one is a ledger row) and **{c['exceptions']}** are listed exceptions ({', '.join(f'{k} {v}' for k, v in c['by_class'].items())}).", "",
         "## The ledger", "",
         "| ledger_id | value | unit | status | status_via | origin | source_line | range_low | range_high | via | anchor | consumers | upgrade_question | source | note |",
         "|" + "---|" * 15]
    esc = lambda s: str(s).replace("|", "/").replace("\n", " ")
    for r in ledger:
        L.append("| " + " | ".join(esc(x) for x in (
            r["ledger_id"], _v(r["value"]), r["unit"], r["status"], r["status_via"], r["origin"], r["source_line"] or "", _v(r["range_low"]), _v(r["range_high"]), r["overridable_via"], r["anchor"],
            _cons(r), "; ".join(r["upgrade_question"]), ledger_anchors.strip_code_lines(r["source"]), ledger_anchors.strip_code_lines(r["note"]))) + " |")
    L += [""] + ledger_notes.render_questions(ledger) + [""] + ledger_notes.render_prose() + [""] + ledger_notes.render_confirmed()
    L += ["", "## Exceptions (numeric constants that are not parameters)", "",
          "| key | class | reason |", "|---|---|---|"]
    for e in exceptions:
        L.append(f"| {esc(e['key'])} | {e['class']} | {esc(e['reason'])} |")
    return "\n".join(L) + "\n"


def render_all():
    ledger, items, exceptions, _ = build()
    return render_md(ledger, items, exceptions), render_csv(ledger)


def main():
    md, csv_text = render_all()
    for path, text in ((MD_PATH, md), (CSV_PATH, csv_text)):
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
    print(f"wrote {MD_PATH} and {CSV_PATH}")


if __name__ == "__main__":
    main()
