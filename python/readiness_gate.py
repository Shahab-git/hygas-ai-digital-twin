"""
Readiness gates for data-driven capabilities (tasks A10 and A10c). INFORMATIONAL ONLY: nothing in the engine, the runtime or the UI reads a gate result to change a value, and the function has no
side effect (it reads two dataclasses and returns a dict).

`readiness_gate(capability, evidence, criteria)` -> {"passes": bool, "reasons": [str], "maturity_allowed": class}.

  * `Evidence` is what exists (counts and flags); `Criteria` holds the numeric thresholds. EVERY criterion defaults to None = "criteria not yet set -- to be fixed with literature task C6 and
    DOK-ING". No number is chosen here for data volume, coverage or error. With a required criterion None the gate cannot pass, and says `criteria not set: <field>`.
  * `reasons` names each required item whose evidence is missing (`missing evidence: <item>`), each criterion that is not set (`criteria not set: <field>`) and each item that is present but
    on the wrong side of its (set) criterion (`below criterion: ...` / `above criterion: ...`). `passes` is True only when `reasons` is empty.
  * `maturity_allowed` is the highest class the EVIDENCE supports, whatever the capability: no plant data and no twin-generated data -> PHYSICS_ESTIMATE; twin-generated data only ->
    SYNTHETIC_BENCHMARK; Measured plant data -> TRAINED_ON_PLANT_DATA; Measured plant data AND a passing `validation` gate -> VALIDATED_ON_HELDOUT. No other capability passing grants the last class.
  * `physical_model_validated` cannot be claimed on its own: `evidence_with_validation_result` sets it only from a passing validation result, and a hand-set True without a passing
    validation gate (re-run here with the same evidence and criteria) is reported as an inconsistency.

REQUIRED is the roadmap's Track D gate table, one row per capability (the minimum evidence before the capability may be called informative):
  calibration            measured inputs and outputs from steady operation at several loads; instrument uncertainties known; identifiability screen passes for each parameter to be fitted;
                         closure residual of the measured balances within measurement uncertainty
  validation             data from operating campaigns NOT used for calibration; stated error metrics per quantity against instrument uncertainty
  virtual_sensing        paired measurements of the target quantity and its inputs across the operating range; a physical model validated at the same level (the validation gate passes);
                         held-out error below the target accuracy of that sensor
  predictive_maintenance degradation or failure history with defined events, not only normal operation; enough events to estimate a survival or trend model with intervals
  optimisation           validated model with uncertainty bounds; constraints taken from the Confirmed design basis; open-loop recommendations compared with operator actions (shadow mode)
  online_replacement     quality gate; drift monitoring; fallback to the last Confirmed value (needs a calibrated model, not necessarily a validated one)
"""
from dataclasses import dataclass, replace
from typing import Optional

from . import maturity as mt


@dataclass(frozen=True)
class Evidence:
    """What exists. Every field defaults to 'missing' (0, None or False)."""
    measured_pairs_count: int = 0                       # Measured (plant) input / output pairs; 0 today
    synthetic_pairs_count: int = 0                      # pairs generated by the twin itself
    operating_range_coverage: Optional[float] = None    # fraction of the operating range covered by Measured data (None = not determined)
    instrument_uncertainty_known: bool = False
    identifiability_screen_passed: bool = False         # for each parameter to be fitted
    balance_closure_within_uncertainty: bool = False    # closure residual of the measured balances within measurement uncertainty
    heldout_campaigns: int = 0
    heldout_data_independent: bool = False              # the held-out campaigns were not used for calibration
    heldout_error: Optional[float] = None               # error on held-out campaigns (None = no held-out evaluation)
    error_metrics_per_quantity: bool = False            # stated per quantity, against instrument uncertainty
    physical_model_validated: bool = False              # only through evidence_with_validation_result
    failure_events_count: int = 0                       # recorded failure / degradation events
    failure_events_defined: bool = False                # the events are defined, not only normal operation recorded
    intervals_reported: bool = False                    # a survival or trend model with intervals can be estimated
    uncertainty_bounds_available: bool = False
    confirmed_envelope_present: bool = False            # constraints taken from the Confirmed design basis
    shadow_mode_comparison_done: bool = False           # open-loop recommendations compared with operator actions
    calibrated_model_available: bool = False
    quality_gate_defined: bool = False
    drift_monitoring_defined: bool = False
    fallback_defined: bool = False                      # fallback to the last Confirmed value


@dataclass(frozen=True)
class Criteria:
    """Thresholds. All None: not yet set (literature task C6 and DOK-ING). Do not put a default number here."""
    min_measured_pairs: Optional[int] = None
    min_operating_range_coverage: Optional[float] = None
    min_heldout_campaigns: Optional[int] = None
    max_heldout_error: Optional[float] = None           # validation: error against instrument uncertainty
    max_target_accuracy: Optional[float] = None         # virtual sensing: held-out error must stay below the target accuracy of that sensor
    min_failure_events: Optional[int] = None


CAPABILITIES = ("calibration", "validation", "virtual_sensing", "predictive_maintenance", "optimisation", "online_replacement")

REQUIRED = {
    "calibration": ("measured_pairs_count", "operating_range_coverage", "instrument_uncertainty_known", "identifiability_screen_passed", "balance_closure_within_uncertainty"),
    "validation": ("heldout_campaigns", "heldout_data_independent", "heldout_error", "error_metrics_per_quantity"),
    "virtual_sensing": ("measured_pairs_count", "operating_range_coverage", "physical_model_validated", "heldout_error"),
    "predictive_maintenance": ("failure_events_count", "failure_events_defined", "intervals_reported"),
    "optimisation": ("physical_model_validated", "uncertainty_bounds_available", "confirmed_envelope_present", "shadow_mode_comparison_done"),
    "online_replacement": ("calibrated_model_available", "quality_gate_defined", "drift_monitoring_defined", "fallback_defined"),
}

# item -> (criteria field, direction); an item not listed here is a flag and needs no criterion. heldout_error is compared with a different criterion per capability.
ITEM_CRITERION = {
    "measured_pairs_count": ("min_measured_pairs", "min"),
    "operating_range_coverage": ("min_operating_range_coverage", "min"),
    "heldout_campaigns": ("min_heldout_campaigns", "min"),
    "failure_events_count": ("min_failure_events", "min"),
}
HELDOUT_ERROR_CRITERION = {"validation": "max_heldout_error", "virtual_sensing": "max_target_accuracy"}
INCONSISTENT = "physical_model_validated claimed without a passing validation gate"


def criterion_for(capability, item):
    """(criteria field, 'min' | 'max') the item is compared with in this capability, or (None, 'flag')."""
    if item == "heldout_error":
        return HELDOUT_ERROR_CRITERION[capability], "max"
    return ITEM_CRITERION.get(item, (None, "flag"))


def _present(evidence, item):
    v = getattr(evidence, item)
    if item in ("operating_range_coverage", "heldout_error"):
        return v is not None
    if isinstance(v, bool):
        return v
    return v > 0


def _reasons(capability, evidence, criteria):
    """The missing-evidence / criteria-not-set / threshold reasons of one capability (no consistency check)."""
    reasons = []
    for item in REQUIRED[capability]:
        field, direction = criterion_for(capability, item)
        have = _present(evidence, item)
        if not have:
            reasons.append(f"missing evidence: {item}")
        if field is not None:
            limit = getattr(criteria, field)
            if limit is None:
                reasons.append(f"criteria not set: {field}")
            elif have:
                value = getattr(evidence, item)
                if direction == "min" and value < limit:
                    reasons.append(f"below criterion: {item} {value} < {field} {limit}")
                if direction == "max" and value > limit:
                    reasons.append(f"above criterion: {item} {value} > {field} {limit}")
    return reasons


def validation_passes(evidence, criteria):
    """True only when the `validation` gate passes for this evidence and these criteria."""
    return not _reasons("validation", evidence, criteria)


def maturity_allowed(evidence, criteria):
    """The highest class the evidence supports (see the module docstring). VALIDATED_ON_HELDOUT needs Measured plant data and a passing validation gate; no other gate grants it."""
    if evidence.measured_pairs_count > 0:
        return mt.VALIDATED_ON_HELDOUT if validation_passes(evidence, criteria) else mt.TRAINED_ON_PLANT_DATA
    if evidence.synthetic_pairs_count > 0:
        return mt.SYNTHETIC_BENCHMARK
    return mt.PHYSICS_ESTIMATE


def evidence_with_validation_result(evidence, validation_result):
    """A copy of `evidence` with physical_model_validated set from a `validation` gate result: True only when that result passed (passes True and no reasons), False otherwise.
    Pass the result of readiness_gate("validation", ...). The gate re-checks the claim against the evidence and criteria it is given, so a wrong result cannot launder the flag."""
    ok = bool(validation_result) and validation_result.get("passes") is True and not validation_result.get("reasons")
    return replace(evidence, physical_model_validated=ok)


def readiness_gate(capability, evidence=None, criteria=None):
    """Pass / fail with the missing evidence and the highest class the evidence supports. Informational; no side effect."""
    if capability not in REQUIRED:
        raise ValueError(f"unknown capability {capability!r}; one of {CAPABILITIES}")
    evidence = evidence if evidence is not None else Evidence()
    criteria = criteria if criteria is not None else Criteria()
    reasons = _reasons(capability, evidence, criteria)
    if evidence.physical_model_validated and not validation_passes(evidence, criteria):
        reasons.append(INCONSISTENT)
    return {"passes": not reasons, "reasons": reasons, "maturity_allowed": maturity_allowed(evidence, criteria)}


# --- the requirement table of the docs, generated from REQUIRED so the two cannot drift apart (tests/test_readiness_gate.py checks the committed docs) ----------------------------------------

TABLE_START = "<!-- REQUIRED:start (generated from python/readiness_gate.REQUIRED; do not edit by hand) -->"
TABLE_END = "<!-- REQUIRED:end -->"


def requirements_markdown():
    """The capability -> required evidence items table, with the criterion each numeric item is compared with."""
    lines = [TABLE_START, "", "| capability | required evidence items (criterion field in brackets) |", "|---|---|"]
    for cap in CAPABILITIES:
        cells = []
        for item in REQUIRED[cap]:
            field, direction = criterion_for(cap, item)
            cells.append(f"`{item}`" + (f" ({'>=' if direction == 'min' else '<='} `{field}`)" if field else ""))
        lines.append(f"| `{cap}` | " + ", ".join(cells) + " |")
    lines += ["", TABLE_END]
    return "\n".join(lines)
