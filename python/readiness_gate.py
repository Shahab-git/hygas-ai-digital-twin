"""
Readiness gates for data-driven capabilities (task A10). INFORMATIONAL ONLY: nothing in the engine, the runtime or the UI reads a gate result to change a value, and the function has no
side effect (it reads two dataclasses and returns a dict).

`readiness_gate(capability, evidence, criteria)` -> {"passes": bool, "reasons": [str], "maturity_allowed": class}.

  * `Evidence` is what exists (counts and flags); `Criteria` holds the numeric thresholds. EVERY criterion defaults to None = "criteria not yet set -- to be fixed with literature task C6 and
    DOK-ING". No number is chosen here for data volume, coverage or error. With a required criterion None the gate cannot pass, and says `criteria not set: <field>`.
  * `reasons` names each required item whose evidence is missing (`missing evidence: <item>`), each criterion that is not set (`criteria not set: <field>`) and each item that is present but
    on the wrong side of its (set) criterion (`below criterion: ...` / `above criterion: ...`). `passes` is True only when `reasons` is empty.
  * `maturity_allowed` is the highest class the EVIDENCE supports, whatever the capability: no plant data and no twin-generated data -> PHYSICS_ESTIMATE; twin-generated data only ->
    SYNTHETIC_BENCHMARK; Measured plant data -> TRAINED_ON_PLANT_DATA; plant data with held-out campaigns that meet both held-out criteria -> VALIDATED_ON_HELDOUT. With the held-out
    criteria None the last step is unreachable.

REQUIRED lists the evidence items per capability. NOT VERIFIED against the roadmap's section 7 table (it is not in this repository): the item names are the ones the task names, and the
assignment to capabilities follows one stated rule -- calibration needs the calibration items, validation adds the held-out items, and each later capability adds its own item to the
validation set. The owner should correct REQUIRED against the roadmap; the tests pin this version.
"""
from dataclasses import dataclass
from typing import Optional

from . import maturity as mt


@dataclass(frozen=True)
class Evidence:
    measured_pairs_count: int = 0                       # Measured (plant) input / output pairs; 0 today
    synthetic_pairs_count: int = 0                      # pairs generated by the twin itself
    operating_range_coverage: Optional[float] = None    # fraction of the operating range covered by Measured data (None = not determined)
    instrument_uncertainty_known: bool = False
    identifiability_screen_passed: bool = False
    heldout_campaigns: int = 0
    heldout_error: Optional[float] = None               # error on held-out campaigns (None = no held-out evaluation)
    failure_events_count: int = 0                       # recorded failure / degradation events usable as labels
    confirmed_envelope_present: bool = False            # a DOK-ING-confirmed operating envelope exists
    fallback_defined: bool = False                      # a defined fallback to the existing control / twin value


@dataclass(frozen=True)
class Criteria:
    """Thresholds. All None: not yet set (literature task C6 and DOK-ING). Do not put a default number here."""
    min_measured_pairs: Optional[int] = None
    min_operating_range_coverage: Optional[float] = None
    min_heldout_campaigns: Optional[int] = None
    max_heldout_error: Optional[float] = None
    min_failure_events: Optional[int] = None


CAPABILITIES = ("calibration", "validation", "virtual_sensing", "predictive_maintenance", "optimisation", "online_replacement")

_CALIBRATION = ("measured_pairs_count", "operating_range_coverage", "instrument_uncertainty_known", "identifiability_screen_passed")
_VALIDATION = _CALIBRATION + ("heldout_campaigns", "heldout_error")
REQUIRED = {
    "calibration": _CALIBRATION,
    "validation": _VALIDATION,
    "virtual_sensing": _VALIDATION,
    "predictive_maintenance": _VALIDATION + ("failure_events_count",),
    "optimisation": _VALIDATION + ("confirmed_envelope_present",),
    "online_replacement": _VALIDATION + ("confirmed_envelope_present", "fallback_defined"),
}

# item -> (criteria field or None, direction): the item must be >= ("min") or <= ("max") the criterion; flags need no criterion
ITEM_CRITERION = {
    "measured_pairs_count": ("min_measured_pairs", "min"),
    "operating_range_coverage": ("min_operating_range_coverage", "min"),
    "heldout_campaigns": ("min_heldout_campaigns", "min"),
    "heldout_error": ("max_heldout_error", "max"),
    "failure_events_count": ("min_failure_events", "min"),
    "instrument_uncertainty_known": (None, "flag"),
    "identifiability_screen_passed": (None, "flag"),
    "confirmed_envelope_present": (None, "flag"),
    "fallback_defined": (None, "flag"),
}


def _present(evidence, item):
    v = getattr(evidence, item)
    if item in ("operating_range_coverage", "heldout_error"):
        return v is not None
    if isinstance(v, bool):
        return v
    return v > 0


def heldout_ok(evidence, criteria):
    """True only when held-out evidence exists AND both held-out criteria are set AND both are met."""
    if criteria.min_heldout_campaigns is None or criteria.max_heldout_error is None:
        return False
    if evidence.heldout_error is None or evidence.heldout_campaigns <= 0:
        return False
    return evidence.heldout_campaigns >= criteria.min_heldout_campaigns and evidence.heldout_error <= criteria.max_heldout_error


def maturity_allowed(evidence, criteria):
    """The highest class the evidence supports (see the module docstring)."""
    if evidence.measured_pairs_count > 0:
        return mt.VALIDATED_ON_HELDOUT if heldout_ok(evidence, criteria) else mt.TRAINED_ON_PLANT_DATA
    if evidence.synthetic_pairs_count > 0:
        return mt.SYNTHETIC_BENCHMARK
    return mt.PHYSICS_ESTIMATE


def readiness_gate(capability, evidence=None, criteria=None):
    """Pass / fail with the missing evidence and the highest class the evidence supports. Informational; no side effect."""
    if capability not in REQUIRED:
        raise ValueError(f"unknown capability {capability!r}; one of {CAPABILITIES}")
    evidence = evidence if evidence is not None else Evidence()
    criteria = criteria if criteria is not None else Criteria()
    reasons = []
    for item in REQUIRED[capability]:
        field, direction = ITEM_CRITERION[item]
        have = _present(evidence, item)
        if not have:
            reasons.append(f"missing evidence: {item}")
        if field is not None:
            limit = getattr(criteria, field)
            if limit is None:
                reasons.append(f"criteria not set: {field}")
            elif have:
                value = getattr(evidence, item)
                if direction == "min" and value < limit:
                    reasons.append(f"below criterion: {item} {value} < {field} {limit}")
                if direction == "max" and value > limit:
                    reasons.append(f"above criterion: {item} {value} > {field} {limit}")
    return {"passes": not reasons, "reasons": reasons, "maturity_allowed": maturity_allowed(evidence, criteria)}
