"""
Maturity classes of the AI / optimisation / virtual-sensing modules (task A10). Pure data and helpers: no Streamlit, no database, no network, nothing here changes a model.

Several modules carry the name of an AI technique but are rule-based, illustrative or run on data generated by the twin itself. This registry says which, in the modules' own words,
so that the UI and each module's docstring can show it and `python/readiness_gate.py` can say what evidence would move a module up a class.

The classes, lowest first (a module that fits two classes takes the LOWER one):
  ILLUSTRATION          demonstrates a method on hypothetical plants or invented data.
  RULE_BASED            fixed rules or thresholds, no fitting.
  PHYSICS_ESTIMATE      a calculation from the twin's own steady-state physics with Assumed / Estimated inputs; no plant data.
  SYNTHETIC_BENCHMARK   trained or tested only on data generated by the twin.
  TRAINED_ON_PLANT_DATA fitted to Measured plant data (none today).
  VALIDATED_ON_HELDOUT  shown against held-out plant data under the readiness gates (none today).

`MATURITY[module]` = {"class", "rationale" (the docstring's own words), "docstring_line" and "docstring_quote" (the file line of the module docstring that supports the class, and the
words on it), "ui_reason" (the short reason shown in the UI caption and in the docstring's MATURITY line), "evidence": None}. `evidence` is None for every module because no plant
data exists in this project; it is the slot a future evidence record goes in. Nothing reads this registry to change a value: it only labels.
"""
