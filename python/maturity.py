def class_of(module):
    """The maturity class of a module. KeyError (not a default) for a module that is not in the registry: an unlabelled module is an error."""
    return MATURITY[module]["class"]


def describe(module):
    """{"module", "class", "rank", "rationale", "ui_reason", "docstring_line", "evidence"}: one dict a UI or a report can print."""
    e = MATURITY[module]
    return {"module": module, "class": e["class"], "rank": rank(e["class"]), "rationale": e["rationale"], "ui_reason": e["ui_reason"], "docstring_line": e["docstring_line"],
            "evidence": e["evidence"]}


def docstring_line(module):
    """The line added to the module's docstring: `MATURITY: <class> — <reason>`."""
    e = MATURITY[module]
    return f"MATURITY: {e['class']} — {e['ui_reason']}"


def caption(module):
    """The one-line UI caption: `Maturity: <class> — <reason> Not validated against plant data.` (no plant data exists; `evidence` is None for every module)."""
    e = MATURITY[module]
    tail = "" if "plant data" in e["ui_reason"] else " Not validated against plant data."
    return f"Maturity: {e['class']} — {e['ui_reason']}{tail}"
